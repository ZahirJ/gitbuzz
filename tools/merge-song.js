#!/usr/bin/env node
/* GitBuzz · merge-song.js
   Builds songs/<id>.js from the source records in sources/<id>/*.json (the "superposition" step).

     node tools/merge-song.js <id>        merge one song
     node tools/merge-song.js --all       merge every song in sources/
     node tools/merge-song.js --check     fail if any songs/<id>.js is out of date with its records
     node tools/merge-song.js <id> --report   also print provenance, conflicts and notes

   Song files are generated: edit the records (usually sources/<id>/manual.json), then re-run. */
'use strict';
const fs = require('fs');
const path = require('path');
const { mergeRecords } = require('../js/merge.js');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'sources');
const args = process.argv.slice(2);
const flag = f => args.includes(f);
const ids = flag('--all') || flag('--check')
  ? fs.readdirSync(SRC).filter(d => fs.statSync(path.join(SRC, d)).isDirectory()).sort()
  : args.filter(a => !a.startsWith('--'));
if (!ids.length) { console.error('usage: merge-song.js <id> | --all | --check [--report]'); process.exit(2); }

function loadRecords(id) {
  const dir = path.join(SRC, id);
  if (!fs.existsSync(dir)) throw new Error(`no sources/${id}/ folder`);
  return fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(f => {
    const r = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    r.file = `sources/${id}/${f}`;
    return r;
  });
}

/* Readable JS literal: short arrays on one line, objects one key per line. */
function fmt(v, ind = 0) {
  const pad = '  '.repeat(ind);
  const flat = x => !Array.isArray(x) && (typeof x !== 'object' || x === null);
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    if (v.every(flat) || (v.every(x => Array.isArray(x) && x.every(flat)) && JSON.stringify(v).length < 110))
      return '[' + v.map(x => fmt(x)).join(', ') + ']';
    return '[\n' + v.map(x => pad + '  ' + fmt(x, ind + 1)).join(',\n') + '\n' + pad + ']';
  }
  if (v && typeof v === 'object') {
    const entries = Object.entries(v).filter(([, x]) => x !== undefined);
    if (!entries.length) return '{}';
    return '{\n' + entries.map(([k, x]) => pad + '  ' + (/^[A-Za-z_]\w*$/.test(k) ? k : JSON.stringify(k)) + ': ' + fmt(x, ind + 1)).join(',\n') + '\n' + pad + '}';
  }
  if (typeof v === 'string') return "'" + v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n') + "'";
  return String(v);
}

function render(song) {
  return `/* GitBuzz song: ${song.name} — ${song.artist}
   GENERATED by tools/merge-song.js from sources/${song.id}/. Do not edit this file;
   edit the source records (usually sources/${song.id}/manual.json) and re-run the merge.
   Chords and structure only. Lyrics stay on the source site (see links). */
GitBuzz.registerSong(${fmt(song)});
`;
}

let stale = 0;
for (const id of ids) {
  const records = loadRecords(id);
  const song = mergeRecords(id, records);
  song.sources.forEach((s, i) => { s.file = records[i].file; });
  const out = path.join(ROOT, 'songs', id + '.js');
  const text = render(song);
  if (flag('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== text) { stale++; console.log(`out of date: songs/${id}.js (run: node tools/merge-song.js ${id})`); }
    continue;
  }
  fs.writeFileSync(out, text);
  console.log(`wrote songs/${id}.js  ←  ${records.map(r => path.basename(r.file)).join(', ')}`);
  if (flag('--report')) {
    console.log('  provenance:', JSON.stringify(song.provenance));
    song.conflicts.forEach(c => console.log(`  conflict: ${c.field}: chose ${c.chosen} (${c.value}) over ${c.other} (${c.otherValue})`));
    song.notes.forEach(n => console.log('  note: ' + n));
  }
}
if (flag('--check')) { console.log(stale ? `${stale} song file(s) out of date` : 'all song files are up to date'); process.exit(stale ? 1 : 0); }
